# ===============================================================
# 题 1：找最大值
# 把昨天写过的循环包成一个函数，传任何列表进来都能算
# 期望：find_max([3, 67, 12, 91, 45, 8]) → 91
# ===============================================================
numbers = [3, 67, 12, 91, 45, 8]
def find_max(numbers):
    # 这里写：假设第一个最大，逐个比较，最后 return
    biggest = numbers[0]
    for n in numbers:
        if n > biggest:
            biggest = n
    return biggest
# ===============================================================
# 题 2：算平均分
# 参数是一个分数列表，返回平均值
# 提示：求和用循环，或者直接用 sum()（这题允许用）
# 期望：average([88, 92, 79]) → 86.333...
# ===============================================================
scores = list(map(int,input("请输入要算平均数的数字").split()))
def average(scores):
    answer = sum(scores) / len(scores)
    return answer

# ===============================================================
# 题 3：判断及格
# 参数是一个分数，60 及以上返回 True，否则返回 False
# 注意：return 后面直接写判断式就行，不需要 if
# 期望：is_pass(59) → False，is_pass(60) → True
# ===============================================================
def is_pass(score):
    if score > 60:
        return True
    else:
        return False


# ===============================================================
# 下面是测试，写完函数后直接运行这个文件
# ===============================================================
if __name__ == "__main__":
    print(find_max([3, 67, 12, 91, 45, 8]))   # 期望 91
    print(average([88, 92, 79]))              # 期望 86.33...
    print(is_pass(59), is_pass(60))           # 期望 False True
