# 第 3 周 D1：字典
# 运行：python week03/day01_dict.py
#
# 字典是"键 → 值"的对应表，用花括号写，键值之间用冒号
# 查字典靠键，不靠位置，所以比列表快

# ===============================================================
# 题 1：建字典 + 增删改查
# 1) 建一个字典 scores，存三个人的成绩
# 2) 打印某一个人的成绩
# 3) 改掉其中一个人的分数
# 4) 新增一个人
# 5) 删除一个人
# 6) 遍历打印所有人和成绩
# ===============================================================
scores = {"深田蓝":100,"隙月":99,"流小莹":101}
print(scores["流小莹"])
scores["流小莹"] = 103
scores["LuneKiss"] = 200
scores.pop("深田蓝")
for name, score in scores.items():
    print(name, score)
# ===============================================================
# 题 2：安全取值
# 用 .get() 查一个不存在的键，不会报错，返回 None 或指定的默认值
# 试着访问一个不存在的名字，分别用 [] 和 .get() 看看区别
# ===============================================================
print(scores.get("dadf")) 
print(scores.get("dadf", 0))
# ===============================================================
# 题 3（重点）：统计每个字出现的次数
# 给一段文字，统计每个字符出现了几次新会话
# 思路：
#   counts = {}
#   for ch in text:
#       if ch in counts:  counts[ch] += 1
#       else:             counts[ch] = 1
# 把上面改成一行（用 .get(ch, 0)）
# ===============================================================
text = "床前明月光，疑是地上霜。举头望明月，低头思故乡。"
counts = {}
for ch in text:
    counts[ch] = counts.get(ch, 0) + 1

print(counts)

